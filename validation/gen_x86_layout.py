"""Generate lean/WriteExecute/X86/LayoutData.lean from validation/layout/{x86,x64}.json.

The layout JSON is produced by validation/extract_layout.py from the assembled COFF objects. The
Lean file records the label offsets and the table entry offsets of the NOT/NZ/SHL4 tables and
proves the structural facts that Fig. 5 relies on (by `decide` on the data).
"""
import json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
out = ["""module
public import WriteExecute.X86.NotTable
public import WriteExecute.Arith.Tables

public section

/-! Generated by validation/gen_x86_layout.py from validation/layout/*.json. Section offsets of the
labels and the table entries in the assembled `writeexc.obj`. -/

namespace WriteExecute.X86

open WriteExecute.Arith
"""]
for arch in ("x86", "x64"):
    d = json.load(open(root / "validation/layout" / f"{arch}.json"))
    L, T = d["labels"], d["tables"]
    for t in ("notres", "nzres", "shlres4"):
        out.append(f"@[expose] def {arch}_{t}_tab : List Nat :=\n  {T[t]['offsets']}\n")
    for k in ("notarg", "notargshl", "notres", "notret", "shlarg4", "shlres4", "shlret4",
              "nzarg", "nzargshl", "nzres", "nzret"):
        out.append(f"@[expose] def {arch}_{k} : Nat := {L[k]}\n")
    a = arch
    out.append(f"""
theorem {a}_geometry :
    {a}_shlres4 = {a}_shlarg4 + 5 + 65536 ∧ {a}_shlret4 = {a}_shlres4 + 9 ∧
    {a}_notargshl = {a}_notarg + 32 ∧ {a}_notres = {a}_notarg + 37 + 4099 ∧
    {a}_notret = {a}_notres + 7 ∧ {a}_shlres4 + 14 ≤ {a}_notarg ∧
    {a}_nzargshl = {a}_nzarg + 32 ∧ {a}_nzres = {a}_nzarg + 37 + 4099 ∧ {a}_nzret = {a}_nzres + 7 := by
  decide

/-- The published layout: the NOT table entries sit at `base + 16 j`, shifted by 3 from entry 248 on. -/
theorem {a}_notres_offsets : ∀ j, j < 256 → {a}_notres_tab.getD j 0 = Eo ({a}_notarg + 37) j :=
  all1 (p := fun j => {a}_notres_tab.getD j 0 = Eo ({a}_notarg + 37) j) (by decide +kernel)

theorem {a}_nzres_offsets : ∀ j, j < 256 → {a}_nzres_tab.getD j 0 = Eo ({a}_nzarg + 37) j :=
  all1 (p := fun j => {a}_nzres_tab.getD j 0 = Eo ({a}_nzarg + 37) j) (by decide +kernel)

theorem {a}_shlres4_offsets : ∀ j, j < 256 → {a}_shlres4_tab.getD j 0 = {a}_shlarg4 + 5 + 256 * j :=
  all1 (p := fun j => {a}_shlres4_tab.getD j 0 = {a}_shlarg4 + 5 + 256 * j) (by decide +kernel)
""")
out.append("end WriteExecute.X86\n")
(root / "lean/WriteExecute/X86/LayoutData.lean").write_text("\n".join(out), encoding="utf-8")
