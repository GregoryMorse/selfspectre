"""Generate lean/WriteExecute/AES/Checks.lean: exhaustive 256-case table checks split into
chunks small enough for kernel evaluation under the 768 MB cap, then recombined."""
CH = 16

def chunked(name, stmt, doc, size=CH, extra_args=""):
    """stmt uses {x} for the index; produces theorem `name : ∀ x, x < 256 → stmt`."""
    out = ""
    n = 256 // size
    for i in range(n):
        out += f"theorem {name}_c{i} : ∀ a, a < {size} → " + stmt.format(x=f"({size*i} + a)") + "\n"
        out += f"  := all1 (p := fun a => " + stmt.format(x=f"({size*i} + a)") + ") (by decide +kernel)\n\n"
    out += f"/-- {doc} -/\ntheorem {name} : ∀ x, x < 256 → " + stmt.format(x="x") + " := by\n  intro x hx\n"
    for i in range(n):
        out += f"  by_cases h{i} : x < {size*(i+1)}\n"
        out += f"  · have := {name}_c{i} (x - {size*i}) (by omega)\n"
        out += f"    rwa [show {size*i} + (x - {size*i}) = x by omega] at this\n"
    out += "  omega\n\n"
    return out

head = '''module
public import WriteExecute.Spec.AES
public import WriteExecute.Arith.Tables

public section

/-! Generated by validation/gen_aes_chunks.py. Exhaustive checks of the AES tables. -/

namespace WriteExecute.AES

open WriteExecute.Arith

'''
body = ""
body += chunked("sbox_alg", "sbox {x} = sboxAlg {x}", "The tabulated S-box is the field inverse followed by the affine map.", 8)
body += chunked("te4_lit", "te4Lit {x} = sbox {x} * 0x01010101", "`Te4` repeats the S-box in every byte.")
body += chunked("sbox_lt", "sbox {x} < 256", "S-box values are bytes.")
for k in range(4):
    stmt = " ∧ ".join(f"lbyte (teLit {k} {{x}}) {m} = mulc (tcoef {k} {4-m}) (sbox {{x}})" for m in (1,2,3,4))
    body += chunked(f"te{k}_bytes", stmt, f"`Te{k}` has the MixColumns coefficients times the S-box value in its bytes.", 16)
mid = ''
tail = "end WriteExecute.AES\n"
import re
body_fixed = body
open("lean/WriteExecute/AES/Checks.lean", "w", encoding="utf-8").write(head + mid + body_fixed + tail)
