"""Generate lean/Challenge.lean mechanically from the Spec modules (plan D6).

The Challenge is the Spec modules reachable from WriteExecute.Spec.Paper (plus the two vendored Base
definition modules they import), concatenated in import order with imports and `theorem` blocks removed,
and a single theorem `PalomarWE.mathematical_result` whose proof is `sorry`.
Usage: python validation/make_challenge.py [--check]   (--check fails when lean/Challenge.lean differs)."""
import re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
LEAN = ROOT / "lean"
TOP = "WriteExecute.Spec.Paper"
HEADER = '''module
public section
/-!
# Write-Execute: selected mathematical result
Gregory Morse, *Self-Spectre, Write-Execute and the Hidden State*, TMMP 73 (2019) 131-144, with the
corrections recorded in lean/errata. The statement selects: read-freedom of the ideal word-level machine
(C01), Turing-completeness with halting, divergence and tape preservation (C02), the finite image (C03),
confinement of finite fetch sets (C04), the jump-table lookup and 8-bit tables (C05-C06), wide arithmetic,
division, modular reduction and exponentiation (C07-C12), AES-128 by T-tables and by the Write-Execute
lookup procedure (C13-C15).
Definitions keep the development's names. Supporting byte-level (x86/x64) and native material is outside
this statement; see PALOMAR_SEMANTICS.md. This file is generated by validation/make_challenge.py from
lean/WriteExecute/Spec/*.lean and lean/WriteExecute/Base/{Memory,Turing}.lean.
The single intentional theorem hole belongs to Challenge; Solution proves it. No custom axiom is assumed.
AI-assisted development; no independent human review is claimed. No submission or registration has been made.
-/
'''
FOOTER = '''namespace PalomarWE
/-- Read-freedom, Turing-completeness, finite image, confinement, lookup and tables, arithmetic and AES
of the corrected Write-Execute paper. -/
theorem mathematical_result : WriteExecute.Paper.ReadFree ∧ WriteExecute.Paper.TuringComplete ∧
    WriteExecute.Paper.FiniteRealization ∧ WriteExecute.Paper.Confinement ∧
    WriteExecute.Paper.Primitives ∧ WriteExecute.Paper.Arithmetic ∧ WriteExecute.Paper.AESResult := by
  sorry
end PalomarWE
'''
def path(m): return LEAN / (m.replace(".", "/") + ".lean")
def imports(m): return re.findall(r"^public import\s+(WriteExecute[\w.]*)", path(m).read_text(encoding="utf-8"), re.M)
def order(m, seen, out):
    if m in seen: return
    seen.add(m)
    for i in imports(m): order(i, seen, out)
    out.append(m)
def body(m):
    text = path(m).read_text(encoding="utf-8").replace("\r\n", "\n")
    text = text.split("public section", 1)[1]
    blocks = re.split(r"\n\s*\n", text.strip("\n"))
    keep = []
    for b in blocks:
        core = re.sub(r"^/--.*?-/\s*", "", b, flags=re.S) if b.lstrip().startswith("/--") else b
        if re.match(r"\s*(theorem|lemma)\b", core): continue
        keep.append(b)
    out = "\n\n".join(keep).strip("\n")
    assert not re.search(r"\b(sorry|axiom|native_decide|unsafe)\b", out), m
    assert not re.search(r"^\s*(theorem|lemma)\b", out, re.M), m
    return out
def build():
    mods = []; order(TOP, set(), mods)
    parts = [HEADER]
    for m in mods:
        parts.append(f"-- ===== {m} =====\n" + body(m) + "\n")
    parts.append(FOOTER)
    return "\n".join(parts)
if __name__ == "__main__":
    new = build(); out = LEAN / "Challenge.lean"
    if "--check" in sys.argv:
        old = out.read_text(encoding="utf-8") if out.exists() else ""
        if old.replace("\r\n", "\n") != new: print("Challenge.lean is out of date"); sys.exit(1)
        print("Challenge.lean up to date"); sys.exit(0)
    out.write_text(new, encoding="utf-8", newline="\n")
    print(f"wrote {out}: {new.count(chr(10))} lines, {len(new.encode('utf-8'))} bytes")
