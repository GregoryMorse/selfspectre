"""Generate validation/native/vectors.h: expected values for the corrected C reference functions
(`mulmod`, `fastmodexp`, `modexp` of spectreopt.c; erratum L02, L03), from exact Python integers
(independent of the Lean development and of the C code). Evidence, not proof."""
import random
from pathlib import Path
random.seed(2019)
M32 = 2**32
edge = [0, 1, 2, 3, 255, 256, 65535, 65536, 65537, 2**31, 2**32 - 3, 2**32 - 2, 2**32 - 1]
mm, me = [], []
for m in [1, 2, 3, 7, 255, 65535, 65536, 65537, 2**31 - 1, 2**31, 2**32 - 5, 2**32 - 1]:
    for a in edge:
        for b in edge:
            mm.append((a, b, m, (a * b) % m))
for _ in range(2000):
    m = random.randrange(1, M32); a = random.randrange(M32); b = random.randrange(M32)
    mm.append((a, b, m, (a * b) % m))
mm.append((65536, 65536, 3, (65536 * 65536) % 3))
for m in [1, 2, 3, 5, 65537, 2**31 - 1, 2**32 - 5, 2**32 - 1]:
    for b in edge:
        for e in [0, 1, 2, 3, 10, 255, 65537, 2**32 - 1]:
            me.append((b, e, m, pow(b, e, m)))
for _ in range(500):
    m = random.randrange(1, M32); b = random.randrange(M32); e = random.randrange(M32)
    me.append((b, e, m, pow(b, e, m)))
def tab(name, rows):
    return "static const struct { uint32_t a, b, m, r; } %s[] = {\n%s\n};\n" % (
        name, ",\n".join("{%du,%du,%du,%du}" % r for r in rows))
Path(__file__).resolve().parent.joinpath("native/vectors.h").write_text(
    "/* generated by validation/gen_vectors.py */\n" + tab("MULMOD", mm) + tab("MODEXP", me), encoding="ascii")
